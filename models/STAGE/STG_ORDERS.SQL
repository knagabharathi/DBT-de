SELECT 
--RAW_ORDERS TABLE 
    O.ORDER_ID,
    O.ORDER_DATE,
    O.SHIP_DATE,
    O.SHIP_MODE,
    O.ORDER_SELLING_PROCE,
    O.ORDER_COST_PRICE,
--RAW_CUSTOMER TABLE
    C.CUSTOMERID,
    C.CUSTOMERNAME,
    C.SEGMENT,
    C.COUNTRY,
--RAW_PRODUCT
    P.PRODUCTID,
    P.CATEGORY,
    P.PRODUCTNAME,
    P.SUBCATEGORY
FROM 
    {{ ref('RAW_ORDERS') }} AS O
LEFT JOIN
    {{ ref('RAW_PRODUCT') }} AS P ON P.PRODUCTID = O.PRODUCT_ID
JOIN
    {{ ref('RAW_CUSTOMER') }} AS C ON O.CUSTOMER_ID = C.CUSTOMERID